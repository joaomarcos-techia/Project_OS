/**
 * DB conventions — single source of truth for column types and naming.
 *
 * Naming (frozen since C0, repeated here for the audience that lands first
 * in the db folder):
 * - Files / folders         : kebab-case
 * - TypeScript identifiers  : camelCase
 * - DB tables               : snake_case plural  (`patients`, `appointments`)
 * - DB columns              : snake_case         (`clinic_id`, `created_at`)
 * - Foreign keys            : `<entity>_id`      (`patient_id`, `clinic_id`)
 *
 * Drizzle converts snake_case (DB) <-> camelCase (TS) automatically when you
 * give it the column name as the first argument:
 *     uuid('clinic_id') -> property `clinicId` in TS.
 *
 * Helpers below codify the patterns every domain table must follow from C2
 * onwards. Do NOT inline these primitives in context schemas — always import
 * from here so future tweaks (e.g. switching defaultRandom() to v7) are one-line.
 */
import { sql } from 'drizzle-orm';
import { timestamp, uuid } from 'drizzle-orm/pg-core';

/**
 * UUID primary key. Generated by Postgres via `gen_random_uuid()` (pgcrypto)
 * exposed by Drizzle as `.defaultRandom()`. Never trust client-generated PKs.
 *
 * Why uuid (vs serial int):
 * - Multi-tenant-safe: no enumerable IDs leaking row counts cross-tenant.
 * - Distributed-safe: future async writers don't fight over a sequence.
 * - Portable: an exported patient row keeps the same id forever.
 */
export const uuidPk = () => uuid('id').primaryKey().defaultRandom();

/**
 * Standard tenant foreign-key column. In C1 there is NO `clinics` table yet,
 * so the FK reference is omitted. In C2 a parallel helper `tenantIdRef()` will
 * add `.references(() => clinics.id, { onDelete: 'cascade' })`. Callers in
 * C2+ should migrate to that helper.
 */
export const tenantId = () => uuid('clinic_id').notNull();

/**
 * Standard timestamp pair. ALL tables that hold mutable rows must include
 * these two columns. `updated_at` is bumped by a generic trigger added in C2.
 *
 * `withTimezone: true` -> Postgres `timestamptz`. We NEVER store naive timestamps:
 * timezones across multi-tenant clinics make naive timestamps an ambiguity bomb.
 */
export const timestampsPattern = () => ({
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .default(sql`now()`),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .default(sql`now()`),
});

/**
 * Soft-delete column. Used by tables where business rules require an "undo"
 * window (e.g. patient LGPD delete -> 30-day soft-delete -> hard-delete).
 * NOT used by every table — only where the runbook specifically calls for it.
 *
 * For LGPD true-delete, a scheduled job (C5) hard-deletes rows where
 * `deleted_at < now() - interval '30 days'`.
 */
export const deletedAt = () => timestamp('deleted_at', { withTimezone: true });
